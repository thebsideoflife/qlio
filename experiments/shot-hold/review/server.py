#!/usr/bin/env python3
"""Local review UI for shot-hold R&D. Stdlib only.

  python review/server.py            # http://localhost:8765

Reads   $SHOTHOLD_CACHE/review/batches/*.json   (cards, generated by make_batch.py)
Serves  $SHOTHOLD_CACHE/review/img/**           (stills)
Appends experiments/shot-hold/labels/labels.jsonl (one JSON line per judgment)

labels.jsonl is append-only. A re-judged card appends a new line; readers take
the last line per (card_id, reviewer).
"""

from __future__ import annotations

import json
import os
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

HERE = Path(__file__).resolve().parent
CACHE = Path(os.environ.get("SHOTHOLD_CACHE", "/tmp/shothold"))
BATCHES = CACHE / "review" / "batches"
IMG = CACHE / "review" / "img"
LABELS = HERE.parent / "labels" / "labels.jsonl"
PORT = int(os.environ.get("PORT", "8765"))


def read_labels() -> dict[str, dict]:
    last: dict[str, dict] = {}
    if LABELS.exists():
        for line in LABELS.read_text().splitlines():
            if line.strip():
                row = json.loads(line)
                last[row["card_id"]] = row
    return last


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *a):  # quiet
        pass

    def _send(self, code: int, body: bytes, ctype: str) -> None:
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _file_range(self, p: Path, ctype: str) -> None:
        size = p.stat().st_size
        start, end = 0, size - 1
        rng = self.headers.get("Range")
        if rng and rng.startswith("bytes="):
            a, _, b = rng[6:].partition("-")
            start = int(a) if a else 0
            end = int(b) if b else size - 1
        with p.open("rb") as f:
            f.seek(start)
            body = f.read(end - start + 1)
        self.send_response(206 if rng else 200)
        self.send_header("Content-Type", ctype)
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        try:
            self.wfile.write(body)
        except (BrokenPipeError, ConnectionResetError):
            pass

    def _json(self, obj, code: int = 200) -> None:
        self._send(code, json.dumps(obj).encode(), "application/json")

    def do_GET(self) -> None:
        path = self.path.split("?")[0]
        if path == "/":
            return self._send(200, (HERE / "index.html").read_bytes(), "text/html")
        if path == "/api/batches":
            labels = read_labels()
            out = []
            for p in sorted(BATCHES.glob("*.json")):
                b = json.loads(p.read_text())
                ids = [c["card_id"] for c in b["cards"]]
                out.append(
                    {
                        "batch_id": b["batch_id"],
                        "title": b.get("title", b["batch_id"]),
                        "n": len(ids),
                        "done": sum(1 for i in ids if i in labels),
                    }
                )
            return self._json(out)
        if path.startswith("/api/batch/"):
            p = BATCHES / (Path(path).name + ".json")
            if not p.exists():
                return self._json({"error": "no such batch"}, 404)
            b = json.loads(p.read_text())
            labels = read_labels()
            for c in b["cards"]:
                c["label"] = labels.get(c["card_id"])
            return self._json(b)
        if path.startswith("/clips/"):
            p = (CACHE / "review" / "clips" / path[len("/clips/"):]).resolve()
            if (CACHE / "review" / "clips").resolve() in p.parents and p.exists():
                return self._file_range(p, "video/mp4")
        if path.startswith("/img/"):
            p = (IMG / path[len("/img/") :]).resolve()
            if IMG.resolve() in p.parents and p.exists():
                return self._send(200, p.read_bytes(), "image/jpeg")
        self._json({"error": "not found"}, 404)

    def do_POST(self) -> None:
        if self.path != "/api/label":
            return self._json({"error": "not found"}, 404)
        row = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
        row["labeled_at"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
        row.setdefault("reviewer", os.environ.get("USER", "unknown"))
        LABELS.parent.mkdir(parents=True, exist_ok=True)
        with LABELS.open("a") as f:
            f.write(json.dumps(row, separators=(",", ":")) + "\n")
        self._json({"ok": True})


if __name__ == "__main__":
    print(f"review UI  http://localhost:{PORT}   cache={CACHE}   labels={LABELS}")
    ThreadingHTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
