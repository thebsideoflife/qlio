function parseS3Uri(uri: string): { bucket: string; key: string } {
  const match = uri.match(/^s3:\/\/([^/]+)\/(.+)$/);
  if (!match) throw new Error(`Invalid S3 URI: ${uri}`);
  return { bucket: match[1], key: match[2] };
}

function isS3NotFound(err: unknown): boolean {
  const e = err as { name?: string; $metadata?: { httpStatusCode?: number } };
  return (
    e.name === "NoSuchKey" ||
    e.name === "NotFound" ||
    e.$metadata?.httpStatusCode === 404
  );
}

async function downloadS3ToFile(
  bucket: string,
  key: string,
  dest: string,
): Promise<void> {
  const obj = await s3Client.send(
    new GetObjectCommand({ Bucket: bucket, Key: key }),
  );
  if (!obj.Body) throw new Error(`Empty S3 object s3://${bucket}/${key}`);
  await pipeline(obj.Body as Readable, createWriteStream(dest));
}

async function putJson(key: string, body: unknown): Promise<void> {
  await s3Client.send(
    new PutObjectCommand({
      Bucket: BUCKET_NAME,
      Key: key,
      Body: JSON.stringify(body),
      ContentType: "application/json",
    }),
  );
}

async function getTranscriptionRunState(
  assetId: string,
): Promise<TranscriptionRunState> {
  const result = await docClient.send(
    new GetCommand({
      TableName: TABLE_NAME,
      Key: { assetId },
      ConsistentRead: true,
      ProjectionExpression:
        "pendingTranscriptionVersion, transcriptionStatus, transcriptionVersion, transcriptionUrl",
    }),
  );
  return result.Item || {};
}

async function transcriptionRunWasCommitted(
  assetId: string,
  transcriptionVersion: string,
): Promise<boolean> {
  return (
    classifyTranscriptionRun(
      await getTranscriptionRunState(assetId),
      transcriptionVersion,
    ) === "committed"
  );
}

async function putJsonForRun(
  assetId: string,
  transcriptionVersion: string,
  key: string,
  body: unknown,
): Promise<void> {
  const before = classifyTranscriptionRun(
    await getTranscriptionRunState(assetId),
    transcriptionVersion,
  );
  if (before === "committed") {
    throw new TranscriptionRunCompletedError(
      `Transcription run ${transcriptionVersion} is already committed`,
    );
  }
  if (before === "superseded") {
    throw new TranscriptionRunSupersededError(
      `Transcription run ${transcriptionVersion} was superseded`,
    );
  }

  await putJson(key, body);

  const state = await getTranscriptionRunState(assetId);
  const after = classifyTranscriptionRun(state, transcriptionVersion);
  if (after === "current") return;

  const committedTranscriptUrl = `s3://${BUCKET_NAME}/${key}`;
  const isCommittedTranscript =
    after === "committed" &&
    state.transcriptionUrl === committedTranscriptUrl &&
    key === originalTranscriptKey(assetId, transcriptionVersion);
  if (!isCommittedTranscript) {
    await s3Client
      .send(new DeleteObjectCommand({ Bucket: BUCKET_NAME, Key: key }))
      .catch(() => undefined);
  }

  if (after === "committed") {
    throw new TranscriptionRunCompletedError(
      `Transcription run ${transcriptionVersion} is already committed`,
    );
  }
  throw new TranscriptionRunSupersededError(
    `Transcription run ${transcriptionVersion} was superseded`,
  );
}

async function loadStoredChunk(
  assetId: string,
  transcriptionVersion: string,
  index: number,
): Promise<StoredWhisperChunk | null> {
  try {
    const obj = await s3Client.send(
      new GetObjectCommand({
        Bucket: BUCKET_NAME,
        Key: whisperChunkKey(assetId, transcriptionVersion, index),
      }),
    );
    const text = await obj.Body?.transformToString();
    if (!text) return null;
    return JSON.parse(text) as StoredWhisperChunk;
  } catch (err) {
    if (isS3NotFound(err)) return null;
    throw err;
  }
}

async function ensurePendingTranscriptionVersion(
  assetId: string,
  asset: Record<string, unknown>,
  requestedVersion?: string,
): Promise<string> {
  const existing =
    typeof asset.pendingTranscriptionVersion === "string"
      ? asset.pendingTranscriptionVersion
      : null;
  if (existing) {
    if (requestedVersion && requestedVersion !== existing) {
      throw new Error(
        `Transcription run ${requestedVersion} was superseded by ${existing}`,
      );
    }
    await docClient.send(
      new UpdateCommand({
        TableName: TABLE_NAME,
        Key: { assetId },
        UpdateExpression: "SET #ts = :pending, updatedAt = :updatedAt",
        ConditionExpression: "pendingTranscriptionVersion = :version",
        ExpressionAttributeNames: { "#ts": "transcriptionStatus" },
        ExpressionAttributeValues: {
          ":pending": "pending",
          ":version": existing,
          ":updatedAt": new Date().toISOString(),
        },
      }),
    );
    return existing;
  }

  const transcriptionVersion = requestedVersion || randomUUID();
  await docClient.send(
    new UpdateCommand({
      TableName: TABLE_NAME,
      Key: { assetId },
      UpdateExpression:
        "SET #ts = :pending, pendingTranscriptionVersion = :version, updatedAt = :updatedAt",
      ConditionExpression:
        "attribute_exists(assetId) AND attribute_not_exists(pendingTranscriptionVersion) AND (attribute_not_exists(#ts) OR #ts = :pending)",
      ExpressionAttributeNames: { "#ts": "transcriptionStatus" },
      ExpressionAttributeValues: {
        ":pending": "pending",
        ":version": transcriptionVersion,
        ":updatedAt": new Date().toISOString(),
      },
    }),
  );
  return transcriptionVersion;
}

