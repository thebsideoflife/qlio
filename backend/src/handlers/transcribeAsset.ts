async function cleanupSupersededTranscripts(
  assetId: string,
  keepKeys: string[],
): Promise<void> {
  const listedKeys = [`transcriptions/${assetId}.json`];
  let continuationToken: string | undefined;
  do {
    const listed = await s3Client.send(
      new ListObjectsV2Command({
        Bucket: BUCKET_NAME,
        Prefix: `transcriptions/${assetId}/`,
        ContinuationToken: continuationToken,
      }),
    );
    for (const item of listed.Contents || []) {
      if (item.Key) listedKeys.push(item.Key);
    }
    continuationToken = listed.IsTruncated
      ? listed.NextContinuationToken
      : undefined;
  } while (continuationToken);

  const staleKeys = selectSupersededTranscriptKeys({
    assetId,
    listedKeys,
    keepKeys,
  });
  for (let index = 0; index < staleKeys.length; index += 1000) {
    const deleted = await s3Client.send(
      new DeleteObjectsCommand({
        Bucket: BUCKET_NAME,
        Delete: {
          Objects: staleKeys
            .slice(index, index + 1000)
            .map((Key) => ({ Key })),
          Quiet: true,
        },
      }),
    );
    if (deleted.Errors?.length) {
      throw new Error(
        `Could not remove ${deleted.Errors.length} superseded transcript object(s): ` +
          deleted.Errors.map((error) => error.Key || error.Code || "unknown").join(", "),
      );
    }
  }
}

async function probeWithFfmpeg(inputPath: string): Promise<string> {
  try {
    const { stderr } = await execFileAsync(FFMPEG_PATH, ["-hide_banner", "-i", inputPath], {
      timeout: 30_000,
      maxBuffer: 2 * 1024 * 1024,
    });
    return String(stderr || "");
  } catch (err) {
    const e = err as { stderr?: string; killed?: boolean };
    if (e.killed) throw new Error("ffmpeg probe timed out");
    return String(e.stderr || "");
  }
}

async function probeMedia(inputPath: string) {
  try {
    const { stdout } = await execFileAsync(
      FFPROBE_PATH,
      [
        "-v",
        "error",
        "-select_streams",
        "a:0",
        "-show_entries",
        "format=start_time,duration:stream=start_time,sample_rate",
        "-of",
        "json",
        inputPath,
      ],
      { timeout: 30_000, maxBuffer: 2 * 1024 * 1024 },
    );
    return parseFfprobeStreamProbe(String(stdout));
  } catch (err) {
    console.warn("[transcribe] ffprobe failed; using container timing fallback", err);
    return parseFfmpegStreamProbe(await probeWithFfmpeg(inputPath));
  }
}

async function readWavInfoFromFile(filePath: string) {
  const fh = await open(filePath, "r");
  try {
    const header = Buffer.alloc(65_536);
    const { bytesRead } = await fh.read(header, 0, header.length, 0);
    return parseWavInfo(header.subarray(0, bytesRead));
  } finally {
    await fh.close();
  }
}

async function measurePcm16Level(
  filePath: string,
  wav: WavInfo,
): Promise<PcmAudioLevel> {
  if (wav.bitsPerSample !== 16) {
    throw new Error(`Cannot measure ${wav.bitsPerSample}-bit PCM audio`);
  }

  let peakAmplitude = 0;
  let sumSquares = 0;
  let sampleCount = 0;
  let carry: Buffer | null = null;
  const stream = createReadStream(filePath, {
    start: wav.dataOffset,
    end: wav.dataOffset + wav.dataBytes - 1,
  });
  for await (const rawChunk of stream) {
    let chunk = Buffer.isBuffer(rawChunk) ? rawChunk : Buffer.from(rawChunk);
    if (carry) {
      chunk = Buffer.concat([carry, chunk]);
      carry = null;
    }
    if (chunk.length % 2 !== 0) {
      carry = chunk.subarray(chunk.length - 1);
      chunk = chunk.subarray(0, chunk.length - 1);
    }
    for (let offset = 0; offset < chunk.length; offset += 2) {
      const amplitude = Math.abs(chunk.readInt16LE(offset)) / 32768;
      peakAmplitude = Math.max(peakAmplitude, amplitude);
      sumSquares += amplitude * amplitude;
      sampleCount += 1;
    }
  }
  return {
    peakAmplitude,
    rmsAmplitude: sampleCount > 0 ? Math.sqrt(sumSquares / sampleCount) : 0,
  };
}


async function loadJobState(
  assetId: string,
  transcriptionVersion: string,
): Promise<SporeLabsJobState | null> {
  try {
    const obj = await s3Client.send(
      new GetObjectCommand({
        Bucket: BUCKET_NAME,
        Key: sporelabsJobStateKey(assetId, transcriptionVersion),
      }),
    );
    const text = await obj.Body?.transformToString();
    if (!text) return null;
    const state = JSON.parse(text) as SporeLabsJobState;
    return typeof state.jobId === "string" && state.jobId ? state : null;
  } catch (err) {
    if (isS3NotFound(err)) return null;
    throw err;
  }
}

async function invokeContinuation(
  context: { invokedFunctionArn?: string },
  payload: {
    assetId: string;
    bucket?: string;
    key?: string;
    hop: number;
    transcriptionVersion: string;
  },
  jobId: string,
): Promise<{ assetId: string; continued: true; jobId: string; hop: number }> {
  const arn = context.invokedFunctionArn;
  if (!arn) {
    throw new Error(`SporeLabs job ${jobId} still running and cannot self-invoke`);
  }
  console.log(
    `[transcribe] SporeLabs job ${jobId} still running; continuing polling in hop ${payload.hop}`,
  );
  await lambdaClient.send(
    new InvokeCommand({
      FunctionName: arn,
      InvocationType: "Event",
      Payload: Buffer.from(JSON.stringify(payload)),
    }),
  );
  return { assetId: payload.assetId, continued: true, jobId, hop: payload.hop };
}

/**
 * Download, extract PCM, stage it, submit. Returns the recorded job state.
 * Honor edit lists / audio delay: do not pass -ignore_editlist or -ss.
 */
async function submitSporeLabsJob(params: {
  assetId: string;
  transcriptionVersion: string;
  bucket: string;
  key: string;
  workDir: string;
  language: string | null;
}): Promise<SporeLabsJobState> {
  const { assetId, transcriptionVersion, bucket, key, workDir, language } = params;
  const sourcePath = path.join(workDir, "source");
  const audioPath = path.join(workDir, "audio.wav");
  console.log(`[transcribe] downloading s3://${bucket}/${key}`);
  await downloadS3ToFile(bucket, key, sourcePath);

  const probe = await probeMedia(sourcePath);
  const audioStartInVideoSec = probe.audioStartSec;
  console.log(
    `[transcribe] container duration=${probe.formatDurationSec}s ` +
      `formatStart=${probe.formatStartSec}s audioStart=${audioStartInVideoSec}s ` +
      `srcHz=${probe.audioSampleRate ?? "?"}`,
  );

  console.log("[transcribe] extracting 16 kHz mono PCM");
  await execFileAsync(
    FFMPEG_PATH,
    [
      "-y",
      "-i",
      sourcePath,
      "-vn",
      "-ac",
      "1",
      "-ar",
      String(WHISPER_SAMPLE_RATE),
      "-c:a",
      "pcm_s16le",
      audioPath,
    ],
    { timeout: 600_000, maxBuffer: 20 * 1024 * 1024 },
  );
  await unlink(sourcePath).catch(() => undefined);

  const wav = await readWavInfoFromFile(audioPath);
  if (wav.sampleRate !== WHISPER_SAMPLE_RATE || wav.channels !== 1) {
    throw new Error(`Unexpected WAV layout: ${wav.sampleRate} Hz ${wav.channels}ch`);
  }
  if (wav.samplesPerChannel < 1) {
    throw new Error("Decoded audio is empty");
  }
  console.log(
    `[transcribe] PCM samples=${wav.samplesPerChannel} ` +
      `duration=${wav.durationSec.toFixed(6)}s ` +
      `(not using container duration ${probe.formatDurationSec}s)`,
  );
  const level = await measurePcm16Level(audioPath, wav);

  const audioKey = transcriptionAudioKey(assetId, transcriptionVersion);
  await s3Client.send(
    new PutObjectCommand({
      Bucket: BUCKET_NAME,
      Key: audioKey,
      Body: createReadStream(audioPath),
      ContentLength: (await stat(audioPath)).size,
      ContentType: "audio/wav",
    }),
  );
  await unlink(audioPath).catch(() => undefined);
  const audioUrl = await getSignedUrl(
    s3Client,
    new GetObjectCommand({ Bucket: BUCKET_NAME, Key: audioKey }),
    { expiresIn: AUDIO_URL_TTL_SECONDS },
  );

  const job = await submitTranscription({
    audio_url: audioUrl,
    duration_seconds: wav.durationSec,
    language,
  });
  console.log(
    `[transcribe] submitted SporeLabs job ${job.id} ` +
      `(${wav.durationSec.toFixed(1)}s of audio, language=${language ?? "detect"})`,
  );

  const state: SporeLabsJobState = {
    jobId: job.id,
    submittedAt: new Date().toISOString(),
    audioKey,
    audio: {
      startInVideo: audioStartInVideoSec,
      sampleRate: wav.sampleRate,
      samples: wav.samplesPerChannel,
      duration: wav.durationSec,
    },
    level,
  };
  await putJsonForRun(
    assetId,
    transcriptionVersion,
    sporelabsJobStateKey(assetId, transcriptionVersion),
    state,
  );
  return state;
}

/** The asset's known language (set by an earlier run, or by hand), or null to detect. */
function knownLanguage(raw: unknown): string | null {
  if (typeof raw !== "string" || !raw.trim()) return null;
  const code = normalizeLanguageCode(raw);
  return /^[a-z]{2,3}$/.test(code) && code !== "und" ? code : null;
}

function sleep(ms: number): Promise<void> {
  return new Promise((r) => setTimeout(r, ms));
}

export const handler: Handler<TranscribeAssetEvent> = async (event, context) => {
  const assetId = event.assetId;
  if (!assetId) throw new Error("assetId is required");
  const hop = parseTranscribeHop(event.hop);
  if (hop >= MAX_SPORELABS_HOPS) {
    throw new Error(`Transcription hit the continuation cap (${MAX_SPORELABS_HOPS})`);
  }

  const workDir = `/tmp/transcribe-${assetId}`;
  await mkdir(workDir, { recursive: true });
  let transcriptionVersion: string | null = null;

  try {
    const assetRes = await docClient.send(
      new GetCommand({
        TableName: TABLE_NAME,
        Key: { assetId },
        ConsistentRead: true,
      }),
    );
    const asset = assetRes.Item;
    if (!asset) throw new Error(`Asset ${assetId} not found`);
    transcriptionVersion = await ensurePendingTranscriptionVersion(
      assetId,
      asset,
      event.transcriptionVersion,
    );

    let bucket = event.bucket;
    let key = event.key;
    if (!bucket || !key) {
      if (typeof asset.s3VideoUrl === "string" && asset.s3VideoUrl.startsWith("s3://")) {
        const parsed = parseS3Uri(asset.s3VideoUrl);
        bucket = parsed.bucket;
        key = parsed.key;
      } else {
        bucket = BUCKET_NAME;
        key =
          typeof asset.key === "string" && asset.key
            ? asset.key
            : `raw/${assetId}.mp4`;
      }
    }
    if (!bucket || !key) {
      throw new Error(`Could not resolve source video for asset ${assetId}`);
    }

    // A retried or continued invocation resumes the recorded job instead of paying twice.
    const state =
      (await loadJobState(assetId, transcriptionVersion)) ??
      (await submitSporeLabsJob({
        assetId,
        transcriptionVersion,
        bucket,
        key,
        workDir,
        language: knownLanguage(asset.originalLanguage),
      }));

    let job: TranscribeJob;
    for (;;) {
      job = await getTranscription(state.jobId);
      if (job.status === "completed") break;
      if (job.status === "failed") {
        throw new Error(
          `SporeLabs transcription ${state.jobId} failed: ` +
            `${job.error?.code ?? "unknown"}: ${job.error?.message ?? ""}`,
        );
      }
      const remaining = context.getRemainingTimeInMillis?.() ?? Number.POSITIVE_INFINITY;
      if (remaining < FINISH_RESERVE_MS + POLL_INTERVAL_MS) {
        if (hop + 1 >= MAX_SPORELABS_HOPS) {
          throw new Error(
            `SporeLabs transcription ${state.jobId} still ${job.status} after ${MAX_SPORELABS_HOPS} hops`,
          );
        }
        return invokeContinuation(
          context,
          { assetId, bucket, key, hop: hop + 1, transcriptionVersion },
          state.jobId,
        );
      }
      await sleep(POLL_INTERVAL_MS);
    }

    const result = job.result;
    if (!result || !Array.isArray(result.segments)) {
      throw new Error(`SporeLabs transcription ${state.jobId} completed without segments`);
    }
    const rawKey = sporelabsRawResponseKey(assetId, transcriptionVersion);
    await putJsonForRun(assetId, transcriptionVersion, rawKey, job);

    const { words, hallucinations } = wordsFromSporeLabsResult(
      result,
      state.audio.startInVideo,
    );
    const flaggedWords = hallucinations.reduce((n, h) => n + h.words.length, 0);
    if (words.length + flaggedWords === 0) {
      if ((result.text || "").trim().length > 0) {
        throw new Error("Whisper returned text but no word timestamps");
      }
      if (state.audio.duration > 1 && !isEffectivelySilent(state.level)) {
        throw new Error(
          `Whisper returned no words for non-silent audio ` +
            `(peak=${state.level.peakAmplitude.toFixed(6)}, rms=${state.level.rmsAmplitude.toFixed(6)})`,
        );
      }
      console.log("[transcribe] accepted silent audio");
    }

    const language = result.language ? normalizeLanguageCode(result.language) : "und";
    const body = {
      language,
      transcriptionVersion,
      model: TRANSCRIBE_MODEL_ID,
      modelSettings: {
        provider: "sporelabs",
        jobId: state.jobId,
        engine: result.engine,
        options: result.options,
      },
      generatedAt: new Date().toISOString(),
      audio: state.audio,
      words,
      hallucinations,
      rawResponse: `s3://${BUCKET_NAME}/${rawKey}`,
    };
    const s3Key = originalTranscriptKey(assetId, transcriptionVersion);
    await putJsonForRun(assetId, transcriptionVersion, s3Key, body);

    const transcriptionUrl = `s3://${BUCKET_NAME}/${s3Key}`;
    await stageTranscriptionReplacement(assetId, {
      transcriptionUrl,
      originalLanguage: language,
      transcriptionVersion,
    });
    await cleanupSupersededTranscripts(assetId, [s3Key, rawKey]);
    await setTranscriptionReady(assetId, transcriptionVersion);
    await s3Client
      .send(new DeleteObjectCommand({ Bucket: BUCKET_NAME, Key: state.audioKey }))
      .catch((err) => console.warn(`[transcribe] could not delete staged audio ${state.audioKey}`, err));

    console.log(
      `[transcribe] wrote ${transcriptionUrl} (${words.length} words, ` +
        `${hallucinations.length} flagged stretch(es) / ${flaggedWords} words held out, ` +
        `lang=${language}, job=${state.jobId}, hop=${hop})`,
    );
    return {
      assetId,
      language,
      words: words.length,
      flaggedWords,
      transcriptionUrl,
      transcriptionVersion,
    };
  } catch (err) {
    let alreadyCommitted = err instanceof TranscriptionRunCompletedError;
    if (!alreadyCommitted && transcriptionVersion) {
      alreadyCommitted = await transcriptionRunWasCommitted(
        assetId,
        transcriptionVersion,
      ).catch(() => false);
    }
    if (alreadyCommitted) {
      console.log(
        `[transcribe] run ${transcriptionVersion} was already committed by another invocation`,
      );
      return {
        assetId,
        transcriptionVersion,
        alreadyCommitted: true,
      };
    }

    console.error("[transcribe] failed:", err);
    if (transcriptionVersion) {
      await setTranscriptionFailed(assetId, transcriptionVersion).catch(
        (statusErr) =>
          console.error("[transcribe] failed to mark status:", statusErr),
      );
    }
    throw err;
  } finally {
    await rm(workDir, { recursive: true, force: true }).catch(() => undefined);
  }
};
